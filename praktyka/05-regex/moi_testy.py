import re
from perevir import perevirka

# ISBN-13 без дефісів: рівно 13 цифр.
VYRAZ = r"^\d{13}$"

TAK = [
    "9780306406157",
    "9780131103627",
    "9791090636071",
    "9783161484100",
    "9780140328721",
    "9791032301234",
]

NI = [
    "978030640615",    # лише 12 цифр
    "97803064061578",  # 14 цифр
    "978030640615A",   # літера замість цифри
    "978-0306406157",  # дефіс
    " 9780306406157",  # пробіл на початку
    "978030640615 ",   # пробіл у кінці
]

perevirka(
    "isbn13",
    "ISBN-13: 13 цифр",
    TAK,
    NI,
    {"isbn13": VYRAZ},
)