
# Робота 5. Ваші регулярні вирази.
# Регулярні вирази перевіряємо у Python.

VYRAZY = {
    # 1. Час від 00:00 до 23:59
    "chas": r"^(?:[01]\d|2[0-3]):[0-5]\d$",
    # Години обмежені діапазоном 00–23, а хвилини — 00–59.

    # 2. Дата дд.мм.рррр, місяць від 01 до 12
    "data": r"^(?:0[1-9]|[12]\d|3[01])\.(?:0[1-9]|1[0-2])\.\d{4}$",
    # Перевіряються формат дня, місяць від 01 до 12 і чотири цифри року.

    # 3. IP-адреса: чотири числа по 1–3 цифри через крапку
    "ip": r"^\d{1,3}(?:\.\d{1,3}){3}$",
    # Адреса складається з чотирьох груп по 1–3 цифри, розділених крапками.

    # 4. Ім'я змінної Python
    "identyfikator": r"^[A-Za-z_][A-Za-z0-9_]*$",
    # Ім'я починається з латинської літери або _, далі можуть бути літери, цифри й _.

    # 5. Лише великі латинські літери, від 3 до 8
    "velyki": r"^[A-Z]{3,8}$",
    # Увесь рядок має містити від трьох до восьми великих латинських літер.

    # 6. Усі слова, довші за 8 літер
    "dovgi_slova": r"\b\w{9,}\b",
    # Межі слів відокремлюють слова, а \w{9,} знаходить слова від дев'яти символів.
}

